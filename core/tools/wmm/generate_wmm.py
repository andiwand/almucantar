#!/usr/bin/env python3
"""Converts a WMM coefficient file (WMM*.COF) to a C++ source file.

    python3 tools/wmm/generate_wmm.py tools/wmm/WMM2025.COF

The output is src/sunradar/internal/wmm_coefficients.cpp. Commit it.
"""

import pathlib
import sys

CORE = pathlib.Path(__file__).resolve().parents[2]
OUT = CORE / "src" / "sunradar" / "internal" / "wmm_coefficients.cpp"
DEGREE = 12


def main(path: pathlib.Path) -> None:
    lines = path.read_text().splitlines()
    epoch_str, name, date = lines[0].split()
    rows = []
    for line in lines[1:]:
        if line.startswith("9999"):
            break
        n, m, g, h, gdot, hdot = line.split()
        rows.append((int(n), int(m), g, h, gdot, hdot))
    expected = [(n, m) for n in range(1, DEGREE + 1) for m in range(0, n + 1)]
    if [(n, m) for n, m, *_ in rows] != expected:
        raise SystemExit(f"{path}: unexpected order or count of coefficients")

    body = "\n".join(
        f"    {{{n}, {m}, {g}, {h}, {gdot}, {hdot}}},"
        for n, m, g, h, gdot, hdot in rows
    )
    OUT.write_text(
        f"""// Generated by tools/wmm/generate_wmm.py from {path.name}. Do not edit.
// {name}, released {date}. Public domain (US government work).

#include "sunradar/internal/wmm.hpp"

namespace sunradar::internal {{

const WmmCoefficients& wmm_coefficients() {{
  static const WmmCoefficients kCoefficients{{
      .name = "{name}",
      .epoch = {epoch_str},
      .terms = {{{{
{body}
      }}}},
  }};
  return kCoefficients;
}}

}}  // namespace sunradar::internal
"""
    )
    print("wrote", OUT)


if __name__ == "__main__":
    main(pathlib.Path(sys.argv[1]))
